// Interpretation: the summary, the top priorities and the three-month plan.
//
// Claude writes these from the measured findings only. Two guards keep it honest:
//
//   1. Figures check. Every number in the model's text must already appear in the
//      findings, scores or page count. A single unmatched number and the whole
//      interpretation is thrown away for the rules-based version below. We never
//      publish a statistic we did not measure.
//   2. Content check. No dollar signs, no prices, and no mention of how the report
//      was produced (we do not foreground our tooling in client-facing copy).
//
// If ANTHROPIC_API_KEY is unset, the call fails, or a guard trips, the rules-based
// interpretation is used. The visitor always gets a complete report.

import Anthropic from '@anthropic-ai/sdk';
import type { CategoryScore, Finding, Interpretation, PlanMonth } from './types';

const MODEL = process.env.AUDIT_MODEL || 'claude-sonnet-5-5';

const SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['summary', 'top_priorities', 'plan'],
  properties: {
    summary: {
      type: 'string',
      description: 'Three or four sentences for the business owner: overall state, the biggest risk, the biggest opportunity.',
    },
    top_priorities: {
      type: 'array',
      description: 'The three to five findings to fix first, most important first.',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['finding_id', 'why'],
        properties: {
          finding_id: { type: 'string', description: 'Exact id of a fail or warn finding.' },
          why: { type: 'string', description: 'One sentence on why this one matters for this business.' },
        },
      },
    },
    plan: {
      type: 'array',
      description: 'Exactly three months.',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['items'],
        properties: { items: { type: 'array', items: { type: 'string' }, description: 'Three to five actions, each a full sentence.' } },
      },
    },
  },
} as const;

const SYSTEM = `You write the summary and action plan for a free website audit from I Love Digital, a Gold Coast digital agency, sent to an Australian small business owner.

Rules you must follow:
- Use only the findings provided. Do not invent problems, causes, figures, percentages, rankings, traffic, revenue or competitor claims.
- Do not write any number that is not already in the findings or scores. When in doubt, describe it in words.
- Never mention prices, costs or dollar figures.
- Never mention how this report was produced, software, or AI tools that wrote it. Talking about AI search tools such as ChatGPT as a place customers search is fine.
- Australian English. No emojis. Plain words a business owner understands.
- Every sentence makes a point, gives the reason, and ends on the benefit to the business. Full sentences, no fragments.
- Confident and warm, never alarmist. Do not use the words "simply", "just" or "unlock".`;

function factsText(findings: Finding[], scores: CategoryScore[], overall: number | null, pagesChecked: number): string {
  return JSON.stringify({
    pages_checked: pagesChecked,
    overall_score: overall,
    scores: scores.map((s) => ({ category: s.label, score: s.score })),
    findings: findings.map((x) => ({
      id: x.id,
      status: x.status,
      priority: x.priority,
      category: x.category,
      title: x.title,
      detail: x.detail,
      fix: x.fix,
      urls: x.urls,
    })),
  });
}

/** Every number written in a string, normalised: "1,200" -> "1200", "2.5" stays. */
export function numbersIn(text: string): string[] {
  return (text.match(/\d[\d,]*(?:\.\d+)?/g) || []).map((n) => n.replace(/,/g, '').replace(/\.0+$/, ''));
}

export function figuresCheck(modelText: string, facts: string): { ok: boolean; unmatched: string[] } {
  const allowed = new Set(numbersIn(facts));
  // Month numbers and small list counts are structure, not statistics.
  ['1', '2', '3', '4', '5'].forEach((n) => allowed.add(n));
  const unmatched = [...new Set(numbersIn(modelText).filter((n) => !allowed.has(n)))];
  return { ok: unmatched.length === 0, unmatched };
}

// "cost" is not banned: "slow pages cost you visitors" is fair. Money words are.
const BANNED = [/\$/, /\bAUD\b/i, /\bpric(e|es|ed|ing)\b/i, /\bfees?\b/i, /\b(claude|anthropic|gpt-?\d|language model|LLM|generated by)\b/i];

export function contentCheck(text: string): { ok: boolean; hit?: string } {
  const hit = BANNED.find((re) => re.test(text));
  return hit ? { ok: false, hit: hit.source } : { ok: true };
}

const MONTHS = ['Month 1: fix what is broken', 'Month 2: strengthen the foundations', 'Month 3: build visibility'];

export function rulesInterpretation(findings: Finding[], overall: number | null, host: string): Interpretation {
  const problems = findings.filter((x) => x.status === 'fail' || x.status === 'warn');
  const fails = findings.filter((x) => x.status === 'fail');
  const critical = problems.filter((x) => x.priority === 'critical');

  const state =
    overall === null
      ? `We checked ${host} across technical SEO, on-page SEO, speed and AI search readiness.`
      : overall >= 85
        ? `${host} is in good shape overall, with a score of ${overall} out of 100 across our checks.`
        : overall >= 60
          ? `${host} has solid foundations but scored ${overall} out of 100, so there is clear room to win more visibility.`
          : `${host} scored ${overall} out of 100, which means several issues are holding it back in Google and with customers.`;
  const risk = critical.length
    ? `The most urgent issue is "${critical[0].title.toLowerCase()}", which should be fixed before anything else.`
    : fails.length
      ? `The first thing to fix is "${fails[0].title.toLowerCase()}", because it directly affects how visitors and search engines see the site.`
      : problems.length
        ? 'There are no serious failures, so the work ahead is about sharpening what is already there.'
        : 'We found nothing that needs urgent attention.';
  const next = problems.length
    ? 'Work through the priorities below in order, and each fix will make the site easier to find and easier to choose.'
    : 'Keep publishing helpful content and keep your details consistent everywhere to stay ahead.';

  // The benefit is the last sentence of each fix ("Do X. Benefit."), so every
  // priority explains itself in its own words rather than a stock line.
  const benefit = (fix: string) => {
    const parts = fix.split(/(?<=\.)\s+/).filter(Boolean);
    return parts.length > 1 ? parts[parts.length - 1] : 'Fixing this improves how Google and visitors judge the site.';
  };
  const top = problems.slice(0, 5).map((x) => ({ findingId: x.id, why: benefit(x.fix) }));

  // Work through the problems in priority order: the most urgent three in month 1,
  // the next four in month 2, the rest in month 3, with an ongoing habit to finish.
  const fixes = problems.map((x) => x.fix).filter(Boolean);
  const ongoing = 'Track clicks and rankings in Google Search Console each month, and publish one helpful article that answers a real customer question.';
  const plan: PlanMonth[] = [
    { month: MONTHS[0], items: fixes.slice(0, 3) },
    { month: MONTHS[1], items: fixes.slice(3, 7) },
    { month: MONTHS[2], items: [...fixes.slice(7, 10), ongoing] },
  ].map((m) => ({ ...m, items: m.items.length ? m.items : [ongoing] }));

  return { summary: [state, risk, next].join(' '), topPriorities: top, plan, source: 'rules' };
}

export async function interpret(args: {
  findings: Finding[];
  scores: CategoryScore[];
  overall: number | null;
  pagesChecked: number;
  host: string;
  business: string | null;
  concern: string | null;
}): Promise<Interpretation> {
  const fallback = rulesInterpretation(args.findings, args.overall, args.host);
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) return fallback;

  const facts = factsText(args.findings, args.scores, args.overall, args.pagesChecked);
  const prompt = `Business: ${args.business || args.host}
Website: ${args.host}
${args.concern ? `The owner's stated concern (address it if the findings relate to it; do not invent findings for it): ${args.concern.slice(0, 600)}\n` : ''}
Measured audit results (JSON):
${facts}

Write the summary, the top priorities (finding ids from fail or warn findings only) and a three-month plan. Month 1 fixes what is broken, month 2 strengthens the foundations, month 3 builds visibility.`;

  try {
    const client = new Anthropic({ apiKey, maxRetries: 1, timeout: 45000 });
    // output_config: structured output and effort, the same shape lib/llm.js uses
    // in ilovedigital-agents. Cast because the SDK typings trail the API.
    const message = await client.messages.create({
      model: MODEL,
      max_tokens: 2500,
      system: SYSTEM,
      messages: [{ role: 'user', content: prompt }],
      output_config: { effort: 'low', format: { type: 'json_schema', schema: SCHEMA } },
    } as unknown as Anthropic.MessageCreateParamsNonStreaming);

    if (message.stop_reason !== 'end_turn') throw new Error(`stop_reason ${message.stop_reason}`);
    const text = message.content
      .filter((b): b is Anthropic.TextBlock => b.type === 'text')
      .map((b) => b.text)
      .join('');
    const parsed = JSON.parse(text) as {
      summary: string;
      top_priorities: { finding_id: string; why: string }[];
      plan: { items: string[] }[];
    };

    const ids = new Set(args.findings.filter((x) => x.status === 'fail' || x.status === 'warn').map((x) => x.id));
    const top = parsed.top_priorities.filter((p) => ids.has(p.finding_id)).slice(0, 5);
    const plan = parsed.plan.slice(0, 3).map((m, i) => ({ month: MONTHS[i], items: m.items.slice(0, 5) }));
    if (plan.length !== 3 || (ids.size > 0 && top.length === 0)) throw new Error('incomplete interpretation');

    const written = [parsed.summary, ...top.map((t) => t.why), ...plan.flatMap((m) => m.items)].join('\n');
    const figures = figuresCheck(written, facts + ' ' + args.host);
    if (!figures.ok) {
      console.warn('[audit] interpretation used unmeasured figures, using rules version:', figures.unmatched);
      return fallback;
    }
    const content = contentCheck(written);
    if (!content.ok) {
      console.warn('[audit] interpretation failed content check, using rules version:', content.hit);
      return fallback;
    }
    return {
      summary: parsed.summary,
      topPriorities: top.map((t) => ({ findingId: t.finding_id, why: t.why })),
      plan,
      source: 'model',
    };
  } catch (e) {
    console.error('[audit] interpretation failed, using rules version:', e);
    return fallback;
  }
}
