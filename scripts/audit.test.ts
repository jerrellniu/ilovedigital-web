// Tests for the instant audit's guards and parsers.
//   npx tsx --test scripts/audit.test.ts

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { isBlockedAddress, normaliseInputUrl, vetAddresses, BlockedUrlError } from '../src/lib/audit/safe-fetch';
import { parseRobots } from '../src/lib/audit/crawl';
import { contentCheck, figuresCheck, rulesInterpretation } from '../src/lib/audit/interpret';
import { score } from '../src/lib/audit/checks';
import type { Finding } from '../src/lib/audit/types';

test('private and reserved addresses are blocked', () => {
  for (const ip of ['127.0.0.1', '10.1.2.3', '172.16.5.5', '192.168.0.1', '169.254.169.254', '100.64.0.1', '0.0.0.0', '::1', 'fd00::1', 'fe80::1', '::ffff:127.0.0.1', '::ffff:10.0.0.1', '::ffff:7f00:1', '::ffff:a9fe:a9fe', '::7f00:1', '0:0:0:0:0:ffff:a00:1', '2002:7f00:1::', '2001:0:1:2::']) {
    assert.equal(isBlockedAddress(ip), true, ip);
  }
  for (const ip of ['1.1.1.1', '142.250.70.78', '2606:4700::1111', '::ffff:808:808', '2002:808:808::']) assert.equal(isBlockedAddress(ip), false, ip);
});

test('unsafe input URLs are refused before any request', () => {
  for (const u of ['file:///etc/passwd', 'http://localhost/', 'http://127.0.0.1/', 'http://[::1]/', 'http://[::ffff:127.0.0.1]/', 'http://[::ffff:169.254.169.254]/', 'http://[::127.0.0.1]/', 'http://169.254.169.254/latest/meta-data/', 'http://example.com:8080/', 'http://user:pass@example.com/', 'intranet']) {
    assert.throws(() => normaliseInputUrl(u), BlockedUrlError, u);
  }
  assert.equal(normaliseInputUrl('example.com.au').toString(), 'https://example.com.au/');
});

test('a hostname that resolves to any private address is refused', () => {
  // The connect-time lookup runs every DNS answer through vetAddresses, so a
  // public-looking name pointed at 127.0.0.1 (or rebinding to it) is refused.
  assert.ok(vetAddresses('evil.example', [{ address: '127.0.0.1' }]) instanceof BlockedUrlError);
  assert.ok(vetAddresses('mixed.example', [{ address: '93.184.216.34' }, { address: '10.0.0.5' }]) instanceof BlockedUrlError);
  assert.ok(vetAddresses('meta.example', [{ address: '::ffff:169.254.169.254' }]) instanceof BlockedUrlError);
  assert.equal(vetAddresses('ok.example', [{ address: '93.184.216.34' }]), null);
  assert.ok(vetAddresses('none.example', []) instanceof Error);
});

test('robots.txt parsing finds full blocks and AI bot blocks', () => {
  const r = parseRobots(`User-agent: GPTBot\nDisallow: /\n\nUser-agent: *\nDisallow: /admin\nSitemap: https://x.com.au/sitemap.xml`);
  assert.equal(r.blocksAll, false);
  assert.deepEqual(r.blockedAiBots, ['GPTBot']);
  assert.deepEqual(r.sitemaps, ['https://x.com.au/sitemap.xml']);
  const all = parseRobots(`User-agent: *\nDisallow: /`);
  assert.equal(all.blocksAll, true);
  assert.ok(all.blockedAiBots.includes('ClaudeBot'));
});

test('figures check rejects numbers that were never measured', () => {
  const facts = JSON.stringify({ detail: '4 page titles fall outside 30 to 65 characters', score: 72 });
  assert.equal(figuresCheck('Your site scored 72 and 4 titles need work.', facts).ok, true);
  const bad = figuresCheck('Fixing this could lift traffic by 40% and 1,200 visits.', facts);
  assert.equal(bad.ok, false);
  assert.deepEqual(bad.unmatched, ['40', '1200']);
});

test('content check blocks pricing and tooling mentions but allows "cost you"', () => {
  assert.equal(contentCheck('Slow pages cost you enquiries.').ok, true);
  assert.equal(contentCheck('AI search tools like ChatGPT read your FAQ.').ok, true);
  assert.equal(contentCheck('We can fix this from $500.').ok, false);
  assert.equal(contentCheck('Our pricing starts low.').ok, false);
  assert.equal(contentCheck('This report was generated by Claude.').ok, false);
});

const finding = (id: string, status: Finding['status'], priority: Finding['priority']): Finding => ({
  id, category: 'technical', status, priority, title: id, detail: 'd', fix: `Fix ${id}.`,
});

test('scores weight priority and the rules plan always has three months', () => {
  const findings = [finding('a', 'fail', 'critical'), finding('b', 'pass', 'low'), finding('c', 'warn', 'medium')];
  const { scores, overall } = score(findings);
  const tech = scores.find((s) => s.category === 'technical')!;
  // (0*4 + 1*1 + 0.5*2) / 7 = 28.6
  assert.equal(tech.score, 29);
  assert.equal(overall, 29);
  const plan = rulesInterpretation(findings, overall, 'x.com.au');
  assert.equal(plan.plan.length, 3);
  assert.ok(plan.plan.every((m) => m.items.length > 0));
  assert.equal(plan.topPriorities[0].findingId, 'a');
  assert.equal(contentCheck(plan.summary).ok, true);
});

test('content check blocks links and email addresses in model text', () => {
  for (const t of ['Visit https://evil.example for the fix', 'See www.evil.example', 'Email help@evil.example today']) {
    assert.equal(contentCheck(t).ok, false, t);
  }
  assert.equal(contentCheck('Add a clear call to action to your homepage.').ok, true);
});
